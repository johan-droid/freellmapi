import { describe, expect, it } from 'vitest';
import { createEmptyTestDb } from '../helpers/test-db.js';
import { normalizeLegacyBooleanColumns } from '../../db/normalize.js';
import { runMigrations } from '../../db/migrate/runner.js';

describe('normalizeLegacyBooleanColumns', () => {
  it('detects and converts legacy boolean columns to BIGINT', async () => {
    const { db, cleanup } = await createEmptyTestDb();

    try {
      // Create a table simulating an old schema with boolean columns
      await db.exec(`
        CREATE TABLE legacy_test_table (
          id SERIAL PRIMARY KEY,
          name TEXT NOT NULL,
          enabled BOOLEAN NOT NULL DEFAULT true,
          supports_vision BOOLEAN NOT NULL DEFAULT false
        );
        INSERT INTO legacy_test_table (name, enabled, supports_vision) VALUES
          ('item_on', true, false),
          ('item_off', false, true);
      `);

      // Verify columns were initially boolean
      const beforeCols = await db.all<{ column_name: string; data_type: string }>(`
        SELECT column_name, data_type
          FROM information_schema.columns
         WHERE table_name = 'legacy_test_table'
         ORDER BY column_name ASC
      `);
      expect(beforeCols.find(c => c.column_name === 'enabled')?.data_type).toBe('boolean');
      expect(beforeCols.find(c => c.column_name === 'supports_vision')?.data_type).toBe('boolean');

      // Run normalization
      await normalizeLegacyBooleanColumns(db);

      // Verify columns are now bigint
      const afterCols = await db.all<{ column_name: string; data_type: string; column_default: string }>(`
        SELECT column_name, data_type, column_default
          FROM information_schema.columns
         WHERE table_name = 'legacy_test_table'
         ORDER BY column_name ASC
      `);
      const enabledCol = afterCols.find(c => c.column_name === 'enabled');
      const visionCol = afterCols.find(c => c.column_name === 'supports_vision');

      expect(enabledCol?.data_type).toBe('bigint');
      expect(visionCol?.data_type).toBe('bigint');
      expect(enabledCol?.column_default).toBe('1');
      expect(visionCol?.column_default).toBe('0');

      // Verify rows converted true -> 1 and false -> 0
      const rows = await db.all<{ name: string; enabled: number; supports_vision: number }>(`
        SELECT name, enabled, supports_vision FROM legacy_test_table ORDER BY id ASC
      `);
      expect(rows).toEqual([
        { name: 'item_on', enabled: 1, supports_vision: 0 },
        { name: 'item_off', enabled: 0, supports_vision: 1 },
      ]);

      // Verify standard integer queries work without casting errors
      await db.run('UPDATE legacy_test_table SET enabled = 0 WHERE name = ?', ['item_on']);
      await db.run('INSERT INTO legacy_test_table (name, enabled, supports_vision) VALUES (?, 1, 0)', ['item_new']);

      const updated = await db.all<{ name: string; enabled: number }>(`
        SELECT name, enabled FROM legacy_test_table WHERE enabled = 1
      `);
      expect(updated.map(u => u.name)).toEqual(['item_new']);
    } finally {
      await cleanup();
    }
  });

  it('allows full migrations to run against a pre-existing table with boolean columns', async () => {
    const { db, cleanup } = await createEmptyTestDb();

    try {
      // Simulate an existing database where models had enabled as boolean
      await db.exec(`
        CREATE TABLE models (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          platform TEXT NOT NULL,
          model_id TEXT NOT NULL,
          display_name TEXT NOT NULL,
          intelligence_rank BIGINT NOT NULL,
          speed_rank BIGINT NOT NULL,
          size_label TEXT NOT NULL DEFAULT '',
          rpm_limit BIGINT,
          rpd_limit BIGINT,
          tpm_limit BIGINT,
          tpd_limit BIGINT,
          monthly_token_budget TEXT NOT NULL DEFAULT '',
          context_window BIGINT,
          enabled BOOLEAN NOT NULL DEFAULT true,
          supports_vision BOOLEAN NOT NULL DEFAULT false,
          UNIQUE(platform, model_id)
        );
      `);

      // Running migrations should NOT crash with "column enabled is of type boolean but expression is of type integer"
      await runMigrations(db, 'up');

      const cols = await db.all<{ column_name: string; data_type: string }>(`
        SELECT column_name, data_type
          FROM information_schema.columns
         WHERE table_name = 'models' AND column_name = 'enabled'
      `);
      expect(cols[0]?.data_type).toBe('bigint');

      // Verify server queries work cleanly
      const count = await db.get<{ cnt: number }>('SELECT COUNT(*) as cnt FROM models WHERE enabled = 1');
      expect(count?.cnt).toBeGreaterThan(0);
    } finally {
      await cleanup();
    }
  });

  it('normalizes legacy fork schema with provider_id, canonical_name, and recovers credentials', async () => {
    const { db, cleanup } = await createEmptyTestDb();

    try {
      // Recreate the exact schema that existed in the fork deployment on Render
      await db.exec(`
        CREATE TABLE providers (
          id SERIAL PRIMARY KEY,
          provider_key VARCHAR(64) UNIQUE NOT NULL,
          display_name VARCHAR(128) NOT NULL,
          base_url TEXT,
          enabled BOOLEAN NOT NULL DEFAULT true
        );

        CREATE TABLE credentials (
          id SERIAL PRIMARY KEY,
          provider_id INTEGER NOT NULL REFERENCES providers(id) ON DELETE CASCADE,
          credential_name VARCHAR(128) NOT NULL DEFAULT '',
          encrypted_value TEXT NOT NULL,
          iv VARCHAR(64) NOT NULL,
          auth_tag VARCHAR(64) NOT NULL,
          enabled BOOLEAN NOT NULL DEFAULT true,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );

        CREATE TABLE models (
          id SERIAL PRIMARY KEY,
          provider_id INTEGER NOT NULL REFERENCES providers(id) ON DELETE CASCADE,
          model_id VARCHAR(128) NOT NULL,
          canonical_name VARCHAR(128) NOT NULL,
          display_name VARCHAR(128) NOT NULL,
          enabled BOOLEAN NOT NULL DEFAULT true,
          context_window INTEGER,
          max_output_tokens INTEGER,
          supports_streaming BOOLEAN NOT NULL DEFAULT true,
          supports_tools BOOLEAN NOT NULL DEFAULT false,
          supports_vision BOOLEAN NOT NULL DEFAULT false,
          supports_structured_output BOOLEAN NOT NULL DEFAULT false,
          supports_reasoning BOOLEAN NOT NULL DEFAULT false,
          platform VARCHAR(64),
          CONSTRAINT uq_provider_model UNIQUE (provider_id, model_id)
        );

        CREATE TABLE client_profiles (
          id SERIAL PRIMARY KEY,
          name VARCHAR(128) NOT NULL,
          api_key VARCHAR(128) UNIQUE NOT NULL,
          system_prompt TEXT,
          enabled BOOLEAN NOT NULL DEFAULT true
        );

        INSERT INTO providers (provider_key, display_name) VALUES ('google', 'Google');
        INSERT INTO credentials (provider_id, credential_name, encrypted_value, iv, auth_tag, enabled)
        VALUES (1, 'My Google Key', 'enc_val_123', 'iv_123', 'tag_123', true);

        INSERT INTO models (provider_id, platform, model_id, canonical_name, display_name)
        VALUES (1, 'google', 'gemini-2.5-flash', 'gemini-2.5-flash', 'Gemini 2.5 Flash');
      `);

      // Running up migrations MUST succeed without violating provider_id not-null constraint
      await runMigrations(db, 'up');

      // Verify models table no longer has provider_id or canonical_name
      const modelCols = await db.all<{ column_name: string; data_type: string }>(`
        SELECT column_name, data_type
          FROM information_schema.columns
         WHERE table_name = 'models'
      `);
      const colNames = new Set(modelCols.map(c => c.column_name));
      expect(colNames.has('provider_id')).toBe(false);
      expect(colNames.has('canonical_name')).toBe(false);
      expect(colNames.has('platform')).toBe(true);

      // Verify models were seeded/migrated cleanly
      const models = await db.all<{ model_id: string; platform: string }>('SELECT model_id, platform FROM models');
      expect(models.length).toBeGreaterThan(10);
      expect(models.some(m => m.platform === 'google' && m.model_id === 'gemini-2.5-flash')).toBe(true);
      expect(models.some(m => m.platform === 'cerebras')).toBe(true);

      // Verify client_profiles table was normalized or created with token_hash
      const cpCols = await db.all<{ column_name: string }>(`
        SELECT column_name
          FROM information_schema.columns
         WHERE table_name = 'client_profiles'
      `);
      const cpNames = new Set(cpCols.map(c => c.column_name));
      expect(cpNames.has('token_hash')).toBe(true);

      // Verify legacy credentials were recovered into api_keys
      const recoveredKeys = await db.all<{ platform: string; encrypted_key: string }>('SELECT platform, encrypted_key FROM api_keys');
      expect(recoveredKeys.some(k => k.platform === 'google' && k.encrypted_key === 'enc_val_123')).toBe(true);
    } finally {
      await cleanup();
    }
  });
});

